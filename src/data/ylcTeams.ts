export type YlcParticipant = {
  name: string;
  email: string;
  accessCode: string;
  role: string;
  teamId: number;
  teamName: string;
};

export const YLC_ACCESS_LIST: YlcParticipant[] = YLC_TEAMS.flatMap((team) =>
  team.members.map((member) => ({
    ...member,
    teamId: team.id,
    teamName: team.name,
  }))
);

export function normalizeAccessCode(value: string) {
  return value.trim().toLowerCase().replace(/\s+/g, "");
}

export function findParticipantByAccessCode(value: string): YlcParticipant | null {
  const code = normalizeAccessCode(value);
  return (
    YLC_ACCESS_LIST.find(
      (person) => normalizeAccessCode(person.accessCode) === code,
    ) ?? null
  );
}

export function getTeamById(teamId: number) {
  return YLC_TEAMS.find((team) => team.id === teamId) ?? null;
}
